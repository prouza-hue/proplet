"""Exercise the deployed admin through its real API and isolated synthetic data.

Requires the private fixture file generated by admin_preview_fixture.py. Never
accepts production hosts or service-role credentials. Email sending is separate.
"""
from pathlib import Path
import argparse
import json
import re
from urllib.parse import urlparse
import httpx


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--url', required=True)
    parser.add_argument('--credentials-file', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    hostname = urlparse(args.url).hostname or ''
    if urlparse(args.url).scheme != 'https' or not re.fullmatch(r'proplet-[a-z0-9-]+-pavel-prouzas-projects\.vercel\.app', hostname):
        parser.error('Only this project preview deployment is permitted')
    fixture = json.loads(args.credentials_file.read_text(encoding='utf-8'))
    if fixture['projectRef'] != 'eanzztstmwlamwfdskbf':
        parser.error('Only the isolated test fixture is permitted')
    report = {'url': args.url, 'syntheticOnly': True, 'checks': []}
    with httpx.Client(base_url=args.url.rstrip('/'), timeout=60, follow_redirects=False) as client:
        config = client.get('/api/config')
        assert config.status_code == 200, f'Public config returned {config.status_code}'
        config = config.json()
        assert config.get('environment') == 'preview' and config.get('adminPreview') is True
        report['checks'].append('exact isolated preview configuration')

        def login(name):
            result = client.post('/api/login', json={'name': name, 'password': fixture['password'], 'family_code': ''})
            assert result.status_code == 200, f'Fixture login failed: {result.status_code}'
            return result.json()

        owner = login(fixture['ownerName'])
        assert owner['id'] == fixture['ownerId']
        headers = {'Authorization': 'Bearer '+owner['token']}
        for endpoint in ('/api/admin/me','/api/admin/workspace','/api/admin/users?limit=2',
                         '/api/admin/teams','/api/admin/support?status=all','/api/admin/reports?status=all',
                         '/api/admin/audit','/api/admin/operations','/api/admin/content?days=7',
                         '/api/admin/analytics','/api/admin/quality','/api/admin/quality-history',
                         '/api/admin/account-integrity','/api/admin/push-diagnostics'):
            result = client.get(endpoint, headers=headers)
            assert result.status_code == 200, f'{endpoint}: {result.status_code} {result.text[:150]}'
            assert result.headers.get('cache-control','').find('no-store') >= 0, endpoint
            report['checks'].append(endpoint+' -> 200 no-store')

        target = fixture['targets'][0]
        listed = client.get('/api/admin/users', params={'q':target}, headers=headers).json()
        detail = client.get('/api/admin/users/'+target, headers=headers).json()
        assert listed['total'] == 1
        assert listed['users'][0]['points'] == detail['stats']['points'] == 2250
        report['checks'].append('exact UUID + authoritative list/detail reward XP')

        cases = client.get('/api/admin/support', params={'status':'all','player_id':target}, headers=headers).json()
        case = next(row for row in cases['reports'] if row['message'].startswith('Testovací případ:'))
        note = 'Ověřeno přes skutečný izolovaný admin API průchod.'
        change = client.patch('/api/admin/support/'+case['id'], headers=headers,
                              json={'status':'resolved','resolution_note':note})
        assert change.status_code == 200, change.text
        archived = client.get('/api/admin/support', params={'status':'resolved','id':case['id']}, headers=headers).json()
        assert archived['total'] == 1 and archived['reports'][0]['resolutionNote'] == note
        audit = client.get('/api/admin/audit', params={'target_id':case['id']}, headers=headers).json()
        assert any(row['action']=='support_report_status' for row in audit['entries'])
        report['checks'].append('case mutation -> resolved archive -> atomic audit')

        other = client.post('/api/login',json={
            'name':'Klára Admin QA','family_code':'SOLO_ADMINQA_'+fixture['targets'][2][:8].upper(),
            'password':fixture['password']}).json()
        assert other.get('id') == fixture['targets'][2]
        for endpoint in ('/api/admin/users','/api/admin/account-integrity','/api/admin/push-diagnostics',
                         '/api/quality-report','/api/quality-history'):
            result = client.get(endpoint, headers={'Authorization':'Bearer '+other['token']})
            assert result.status_code == 403, f'Second owner grant accepted at {endpoint}'
        report['checks'].append('second DB owner refused, including historical aliases')
        assert client.get('/api/admin/users').status_code == 401
        report['checks'].append('unauthenticated API refused')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print('PASS: '+str(len(report['checks']))+' real preview API checks; synthetic data only')


if __name__ == '__main__':
    main()
